"""Add grating-coupler labels to the KLayout screenshots and the author signature
to the images that are not generated by a plotting script (hand-drawn schematics,
KLayout screenshots). Originals are kept in
figures/source/, signed copies are written to figures/.
Run from the repository root:  python analysis/stamp_images.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "figures" / "source"
OUT = ROOT / "figures"
SIGNATURE = "© Riadh Ben Abbes 2026"
INK = (25, 25, 35)

# grating-coupler labels on the KLayout screenshots: (text, x, y) in source pixels,
# text anchored by its left edge, placed next to each coupler
GC_LABELS = {
    "fig06_layout_klayout.png": [("Output GC1", 18, 78), ("Input GC", 18, 335),
                                 ("Output GC2", 18, 592), ("Output GC3", 18, 760),
                                 ("1×4 demux", 490, 222), ("Test MZI 1", 700, 622),
                                 ("Test MZI 2", 1062, 520)],
    "fig06b_layout_duplicate_klayout.png": [("Output GC4", 18, 73), ("Input GC", 18, 335),
                                            ("1×4 demux", 490, 222)],
}


def stamp(path):
    im = Image.open(path).convert("RGB")
    d = ImageDraw.Draw(im)
    if path.name in GC_LABELS:
        try:
            bold = ImageFont.truetype("DejaVuSans-Bold.ttf", max(14, im.width // 75))
        except OSError:
            bold = ImageFont.load_default()
        for text, x, y in GC_LABELS[path.name]:
            d.text((x, y), text, fill=INK, font=bold)
    size = max(11, im.width // 70)
    try:
        font = ImageFont.truetype("DejaVuSans.ttf", size)
    except OSError:
        font = ImageFont.load_default()
    w = d.textlength(SIGNATURE, font=font)
    x, y = im.width - w - size * 0.8, im.height - size * 1.6
    d.text((x, y), SIGNATURE, fill=(140, 140, 150), font=font)
    im.save(OUT / path.name, optimize=True)


if __name__ == "__main__":
    for f in sorted(SRC.glob("*.png")):
        stamp(f)
        print("signed", f.name)
